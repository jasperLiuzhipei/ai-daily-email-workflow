#!/usr/bin/env python3
"""Send a generated .eml email package through SMTP.

Safety defaults:
- This script dry-runs by default. Add --send to actually send.
- Recipients should come from --recipient-list test/prod or --to.
- SMTP credentials are read from environment variables or CLI args; do not
  commit passwords into this repository.
"""

from __future__ import annotations

import argparse
import getpass
import os
import smtplib
from email import policy
from email.parser import BytesParser
from email.utils import getaddresses
from pathlib import Path

from email_recipients import (
    DEFAULT_RECIPIENT_CONFIG,
    RecipientError,
    email_only,
    formatted_addresses,
    resolve_recipients,
)


def env_value(name: str, fallback: str | None = None) -> str | None:
    return os.environ.get(name) or fallback


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Dry-run or send an AI daily .eml package through SMTP.")
    parser.add_argument("eml", type=Path, help="Input .eml path generated by create_email_send_package.py.")
    parser.add_argument("--recipient-list", choices=["test", "prod"], help="Named recipient list.")
    parser.add_argument("--recipient-config", type=Path, default=DEFAULT_RECIPIENT_CONFIG, help="Recipient config JSON path.")
    parser.add_argument("--to", action="append", default=[], help="Extra recipient. Can be repeated.")
    parser.add_argument("--from-addr", default=env_value("AI_DAILY_FROM_ADDR"), help="Envelope/header From.")
    parser.add_argument("--smtp-host", default=env_value("AI_DAILY_SMTP_HOST"), help="SMTP host.")
    parser.add_argument("--smtp-port", type=int, default=int(env_value("AI_DAILY_SMTP_PORT", "465")), help="SMTP port.")
    parser.add_argument(
        "--smtp-security",
        choices=["ssl", "starttls", "none"],
        default=env_value("AI_DAILY_SMTP_SECURITY", "ssl"),
        help="SMTP transport security.",
    )
    parser.add_argument("--smtp-user", default=env_value("AI_DAILY_SMTP_USER"), help="SMTP username.")
    parser.add_argument("--smtp-password", default=env_value("AI_DAILY_SMTP_PASSWORD"), help="SMTP password or auth token.")
    parser.add_argument("--ask-password", action="store_true", help="Prompt for SMTP password at runtime.")
    parser.add_argument("--send", action="store_true", help="Actually send. Without this flag, only dry-run checks.")
    return parser.parse_args()


def set_header(msg, key: str, value: str) -> None:
    if key in msg:
        msg.replace_header(key, value)
    else:
        msg[key] = value


def count_inline_images(msg) -> int:
    return sum(1 for part in msg.walk() if part.get_content_type().startswith("image/") and part.get("Content-ID"))


def html_has_cid_images(msg) -> bool:
    for part in msg.walk():
        if part.get_content_type() == "text/html":
            try:
                return "cid:" in part.get_content()
            except LookupError:
                payload = part.get_payload(decode=True) or b""
                return b"cid:" in payload
    return False


def current_header_recipients(msg) -> list[str]:
    values = [msg.get("To", ""), msg.get("Cc", ""), msg.get("Bcc", "")]
    return [email for _, email in getaddresses(values) if email]


def send_message(args: argparse.Namespace, msg, recipient_emails: list[str]) -> None:
    if not args.smtp_host:
        raise SystemExit("Send failed: missing --smtp-host or AI_DAILY_SMTP_HOST.")

    password = args.smtp_password
    if args.ask_password and not password:
        password = getpass.getpass("SMTP password: ")

    if args.smtp_security == "ssl":
        server = smtplib.SMTP_SSL(args.smtp_host, args.smtp_port, timeout=30)
    else:
        server = smtplib.SMTP(args.smtp_host, args.smtp_port, timeout=30)

    with server:
        server.ehlo()
        if args.smtp_security == "starttls":
            server.starttls()
            server.ehlo()
        if args.smtp_user:
            server.login(args.smtp_user, password or "")
        server.send_message(msg, from_addr=args.from_addr, to_addrs=recipient_emails)


def main() -> None:
    args = parse_args()
    eml_path = args.eml.resolve()
    if not eml_path.exists():
        raise SystemExit(f"Send failed: missing .eml file: {eml_path}")

    try:
        recipients = resolve_recipients(args.recipient_list, args.to, args.recipient_config)
    except RecipientError as exc:
        raise SystemExit(f"Send failed: {exc}") from exc

    msg = BytesParser(policy=policy.SMTP).parsebytes(eml_path.read_bytes())
    if recipients:
        to_addrs = formatted_addresses(recipients)
        recipient_emails = email_only(recipients)
        set_header(msg, "To", ", ".join(to_addrs))
    else:
        recipient_emails = current_header_recipients(msg)
        to_addrs = [msg.get("To", "")]

    if not recipient_emails:
        raise SystemExit("Send failed: no recipients. Use --recipient-list test/prod or --to.")
    if not args.from_addr:
        raise SystemExit("Send failed: missing --from-addr or AI_DAILY_FROM_ADDR.")

    set_header(msg, "From", args.from_addr)

    print("AI Daily SMTP send check")
    print(f"EML: {eml_path}")
    print(f"Subject: {msg.get('Subject')}")
    print(f"From: {msg.get('From')}")
    print(f"Recipients: {len(recipient_emails)}")
    for address in to_addrs:
        if address:
            print(f"- {address}")
    print(f"HTML has cid: {html_has_cid_images(msg)}")
    print(f"Inline images: {count_inline_images(msg)}")

    if not args.send:
        print("Dry-run only. Add --send after SMTP settings are confirmed.")
        return

    try:
        send_message(args, msg, recipient_emails)
    except smtplib.SMTPAuthenticationError as exc:
        raise SystemExit(f"Send failed: SMTP authentication failed: {exc.smtp_code} {exc.smtp_error!r}") from exc
    except smtplib.SMTPRecipientsRefused as exc:
        raise SystemExit(f"Send failed: SMTP recipients refused: {exc.recipients!r}") from exc
    except smtplib.SMTPResponseException as exc:
        raise SystemExit(f"Send failed: SMTP error: {exc.smtp_code} {exc.smtp_error!r}") from exc
    except OSError as exc:
        raise SystemExit(f"Send failed: network/connection error: {exc}") from exc
    print("Sent.")


if __name__ == "__main__":
    main()
